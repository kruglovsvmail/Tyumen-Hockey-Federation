// Подпись: вместо собственноручной — галочка, которую человек ставит в форме на сайте.
// Рисуем её вектором (canvas), а не символом ✓: гарантии, что нужный глиф есть
// в подключённом шрифте, нет, а отсутствующий глиф в PDF молча превращается в пустоту.
// В пустом бланке (его показывают на сайте «прочитать текст согласия») клетка пустая:
// заполненная галочка на неподписанном образце вводила бы в заблуждение.
