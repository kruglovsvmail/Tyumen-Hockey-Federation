/**
 * Собирает docDefinition для pdfmake: оба согласия в одном файле, второе с новой страницы.
 *
 * @param {object} data
 * @param {string} data.fullName             ФИО полностью в именительном падеже
 * @param {string} data.initials             расшифровка подписи вида «И.И. Иванов»
 * @param {string} data.passportSeries       серия документа, удостоверяющего личность
 * @param {string} data.passportNumber       номер документа
 * @param {string} data.passportIssueDate    дата выдачи, дд.мм.гггг
 * @param {string} data.passportIssuedBy     орган, выдавший документ
 * @param {string} data.registrationAddress  адрес регистрации
 * @param {string} data.phone                контактный номер телефона
 * @param {string} data.signedAtDate         дата подписания, дд.мм.гггг
 * @param {string} data.signedAtTime         время подписания, чч:мм (для служебной строки)
 * @param {string} data.documentCode         код документа для сверки с записью в системе
 */
export const buildConsentDocDefinition = (data) => ({
  pageSize: 'A4',
  // Каждое согласие обязано умещаться в один лист А4 — их подписывают и печатают
  // поштучно, и второй лист с одним абзацем и подписью выглядит как потерянный документ.
  // Отсюда мелкий кегль и узкие поля: текст согласий переписать нельзя, а он очень
  // плотный. Правя шаблон, проверяй, что документ не разъехался на две страницы.
  pageMargins: [36, 22, 28, 26],
  defaultStyle: { font: 'Serif', fontSize: 7.5, lineHeight: 1.04 },

  // Служебная строка внизу каждой страницы: по коду документа лига находит запись
  // о подписании (roster_consent_signatures) и может подтвердить подлинность файла.
  footer: (currentPage, pageCount) => ({
    columns: [
      {
        text: data.documentCode
          ? `Документ сформирован автоматически на сайте ТГОО «ФХ» ${data.signedAtDate} ${data.signedAtTime}. `
            + `Код документа: ${data.documentCode}`
          : 'Образец бланка для ознакомления. Документ не заполнен и не подписан.',
        style: 'footerNote',
      },
      { text: `${currentPage} / ${pageCount}`, style: 'footerNote', alignment: 'right', width: 50 },
    ],
    // Левое и правое поля — те же, что у страницы, иначе служебная строка не совпадает
    // по краю с текстом документа.
    margin: [36, 8, 28, 0],
  }),

  content: [
    ...consentProcessing(data),
    { text: '', pageBreak: 'before' },
    ...consentDistribution(data),
  ],

  styles: {
    title: { fontSize: 9.5, bold: true, alignment: 'center' },
    clause: { alignment: 'justify', margin: [0, 2.2, 0, 0] },
    fieldLabel: { bold: true, margin: [0, 3.5, 0, 0] },
    fieldValue: { alignment: 'center', margin: [0, 1, 0, 0] },
    fieldCaption: { fontSize: 6.5, alignment: 'center', margin: [0, 0.5, 0, 0] },
    signValue: { alignment: 'center' },
    signCaption: { fontSize: 6.5, alignment: 'center', margin: [0, 0.5, 0, 0] },
    footnote: { fontSize: 6.2, alignment: 'justify', lineHeight: 1.02 },
    footerNote: { fontSize: 6, color: '#555555' },
  },
});
